export interface Frame {
  width: number;
  height: number;
  pixels: Uint8ClampedArray<ArrayBuffer>;
}

export function decodeFrame(buf: ArrayBuffer): Frame {
  const view = new DataView(buf);
  const width = view.getUint32(0, true);
  const height = view.getUint32(4, true);
  if (buf.byteLength !== 8 + width * height * 4) {
    throw new Error(`corrupt frame: ${buf.byteLength} bytes for ${width}x${height}`);
  }
  return { width, height, pixels: new Uint8ClampedArray(buf, 8) };
}
