/// Glyph columns for `c`; unknown characters render as `?`.
pub fn glyph(c: char) -> &'static [u8; 5] {
    let code = c as u32;
    let idx = if (32..=126).contains(&code) {
        code - 32
    } else {
        '?' as u32 - 32
    };
    &GLYPHS[idx as usize]
}

/// Is font pixel `(col, row)` of `c` lit? `row` 0 is the top.
pub fn lit(c: char, col: usize, row: usize) -> bool {
    col < GLYPH_W && row < GLYPH_H && glyph(c)[col] >> row & 1 == 1
}

/// Width and height of `text` in nm when the glyph height is `height`.
pub fn text_extent(text: &str, height: Coord) -> (Coord, Coord) {
    let n = text.chars().count() as Coord;
    let px = (height / GLYPH_H as Coord).max(1);
    (
        (n * ADVANCE as Coord - 1).max(0) * px,
        GLYPH_H as Coord * px,
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_glyphs() {
        // 'I' has a vertical bar in the middle column over all rows.
        assert!((0..7).all(|r| lit('I', 2, r)));
        // '-' is a single row.
        assert!((0..5).all(|c| lit('-', c, 3)) && !lit('-', 0, 0));
        assert_eq!(glyph('é'), glyph('?'));
    }

    #[test]
    fn extent_scales_with_height() {
        let (w1, h1) = text_extent("AB", 7);
        let (w2, h2) = text_extent("AB", 14);
        assert_eq!((w2, h2), (w1 * 2, h1 * 2));
        assert_eq!(text_extent("", 7).0, 0);
    }
}
